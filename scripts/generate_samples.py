"""Run the required privacy/approval scenarios once and write sample trace + audit records to reports/sample_audit_trace.md."""
import sys
from dataclasses import replace
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config.settings import ROOT, Settings           # noqa: E402
from services.evaluation import EvalEnv               # noqa: E402


def table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    env = EvalEnv(replace(Settings.from_env(False), model_provider="mock"))
    script = [("S1001", "What is my current fee status?"), ("S1001", "What is the fee status for S1002?"),
              ("S1001", "I want to change my course to Machine Learning because I like it"),
              ("S1002", "I want to change my course to Business"), ("S1001", "my OTP is 482913, please remember it")]
    traces = []
    for who, msg in script:
        r = env.chat(who, msg)
        traces.append(env.svc.tracer.get(r.run_id))
    p = env.svc.approvals.list_pending(env.ctx("approver"))
    env.svc.approvals.decide(env.ctx("approver"), p[-1]["id"], "APPROVE", "seats available")        # oldest first
    r2 = env.chat("S1002", "change my course to DS503")                                             # course is full -> validation
    traces.append(env.svc.tracer.get(r2.run_id))
    other = env.svc.approvals.request_course_change(env.ctx("S1002"), "BDA502")
    env.svc.approvals.decide(env.ctx("approver"), other["approval_id"], "REJECT", "demo rejection")
    md = ["# Sample trace and audit records (generated by scripts/generate_samples.py from a real run)", "",
          "Mock provider; tokens are `unavailable` because the mock reports no usage.", "", "## Agent traces", "",
          table([{"user": t["role"] + ":" + str(t["student_id"]), "question": t["question"], "decision": t["decision"],
                  "authorization": ", ".join(f"{a['tool']}={a['permission']}" for a in t["authorization"]) or "-",
                  "approval_state": t["approval_state"] or "-", "outcome": t["outcome"], "latency_ms": t["latency_ms"],
                  "tokens": t["token_source"]} for t in traces],
                ["user", "question", "decision", "authorization", "approval_state", "outcome", "latency_ms", "tokens"]),
          "", "## Audit events (oldest first)", "",
          table([{**e, "detail": e["detail"] or ""} for e in env.audit()],
                ["timestamp", "actor", "actor_role", "action", "target_type", "target_id", "permission_decision",
                 "approval_request_id", "approval_decision", "approver_user_id", "execution_status", "result", "error_category"]), ""]
    chain = env.svc.audit.verify_chain_system()
    md += ["## Audit hash-chain verification", "", f"intact={chain['ok']}, events checked={chain['checked']}, head hash=`{chain['head_hash']}`", ""]
    (ROOT / "reports" / "sample_audit_trace.md").write_text("\n".join(md))
    env.close()
    print("written reports/sample_audit_trace.md")


if __name__ == "__main__":
    main()
